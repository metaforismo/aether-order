/** Parse the §6.1 closest-pairs table out of the document. */
function documentedClosestPairs() {
  const start = DESIGN.indexOf('<!-- palette:closest-pairs:start -->');
  const end = DESIGN.indexOf('<!-- palette:closest-pairs:end -->');
  expect(start, 'docs/DESIGN.md is missing the closest-pairs markers').toBeGreaterThan(-1);
  expect(end).toBeGreaterThan(start);
  const rows = [];
  for (const line of DESIGN.slice(start, end).split('\n')) {
    const match = line.match(/^\|\s*(\d+)\s*\|\s*([A-Z]+↔[A-Z]+)\s*\|\s*(\d+\.\d{2}:1)\s*\|\s*(yes|no)\s*\|/u);
    if (match) rows.push({ rank: Number(match[1]), pair: match[2], ratio: match[3], inClassic: match[4] === 'yes' });
  }
  return rows;
}

