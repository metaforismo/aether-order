/**
 * The rendering budget and the colour-separation bound, recomputed.
 *
 * Two round-2 defects motivated this file, and both share a shape: a table that
 * looked like arithmetic and was never run.
 *
 *   1. docs/DESIGN.md §7.1 computed every GPU pass in CSS-logical pixels. GPUs
 *      shade device pixels, and the three named reference devices run at DPR 2,
 *      2.6 and ~2.75, so the published load was understated by a factor of four
 *      to nine. The conclusion held; the figures did not.
 *   2. §15 prescribed two replacement sphere hexes to repair colour-blind
 *      separation. Both *reduced* the luminance separation of the pair they
 *      were prescribed to repair — #3D8BFF against VIOLET is 1.05:1, down from
 *      1.24:1. The instruction to "re-check every ratio" was an admission the
 *      check had never been run, and a named hex in a production spec gets
 *      actioned by whoever picks up the ticket.
 *
 * So: the pass table is generated by `tools/lib/framebudget.mjs` and asserted
 * against the document here, and the colour claim is replaced by a bound this
 * file proves — under a 4.5:1 floor against `--void`, seven colours cannot be
 * separated by luminance, whatever hexes anyone picks.
 *
 * Round 4 then added a third of the same shape, one layer up: §6.1's "closest
 * pairs" list was typed by hand, every ratio in it was correct, and the SET was
 * wrong — it omitted AMBER↔ROSE (third) and published the fifth-closest. The
 * test below it sorted all 21 pairs and asserted only `pairs[0]` and four
 * substring matches, so it checked the numbers and never the claim. The list is
 * now generated by `tools/lib/palette.mjs` and the claim itself is asserted:
 * the published rows ARE the k closest pairs, in order.
 */

