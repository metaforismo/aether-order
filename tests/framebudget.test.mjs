describe('the budget model behaves', () => {
  it('caps the backing store on every reference device above the cap', () => {
    for (const device of REFERENCE_DEVICES) {
      const budget = frameBudget({ devicePixelRatio: device.devicePixelRatio });
      expect(budget.effectiveDpr).toBe(Math.min(device.devicePixelRatio, BACKING_STORE_DPR_CAP));
      expect(budget.capped).toBe(device.devicePixelRatio > BACKING_STORE_DPR_CAP);
      // Capping means every device pays the same chamber cost.
      expect(budget.shadedFragments).toBe(capped.shadedFragments);
    }
  });

  it('scales quadratically with the ratio when uncapped', () => {
    const one = frameBudget({ devicePixelRatio: 1, dprCap: null });
    const two = frameBudget({ devicePixelRatio: 2, dprCap: null });
    expect(two.shadedFragments / one.shadedFragments).toBeCloseTo(4, 1);
  });

  it('the composite pass is the only full-resolution one', () => {
    const full = capped.rows.filter((row) => row.scale === 1);
    expect(full).toHaveLength(1);
    expect(full[0].targetPixels).toBe(CHAMBER_CSS.width * 2 * CHAMBER_CSS.height * 2);
  });

  it('stays far inside a mid-range part even uncapped at the worst reference ratio', () => {
    const worst = frameBudget({ devicePixelRatio: 3, dprCap: null });
    // 1 Gfrag/s is the low end of the named class; the budget must not need it.
    expect(worst.megafragmentsPerSecond).toBeLessThan(500);
    // 10 GB/s is the low end of the named memory bandwidth.
    expect(worst.trafficMegabytesPerSecond).toBeLessThan(5000);
  });
});

/* ------------------------------------------------------------------ *
 * 2. Luminance cannot be the colour-blind channel. Proved.             *
 * ------------------------------------------------------------------ */

const channel = (value) => {
  const c = value / 255;
  return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
};
const luminance = (hex) => {
  const n = Number.parseInt(hex.slice(1), 16);
  return 0.2126 * channel((n >> 16) & 255) + 0.7152 * channel((n >> 8) & 255) + 0.0722 * channel(n & 255);
};
const contrast = (a, b) => {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
};

const VOID = '#05070C';
const FLOOR = 4.5;

describe('the SEVEN colour-separation question, answered arithmetically', () => {
  it('every sphere clears the foreground floor against the void', () => {
    for (const element of ELEMENTS) {
      expect(contrast(element.hex, VOID), element.id).toBeGreaterThanOrEqual(FLOOR);
    }
  });

  it('the floor bounds how far apart any two of seven colours can be in luminance', () => {
    // A colour at ratio >= 4.5:1 against the void has (L + 0.05) >= 4.5 * (Lv + 0.05).
    // The brightest possible colour is white, at (1 + 0.05). So the whole set
    // lives inside a contrast span of:
    const span = 1.05 / (FLOOR * (luminance(VOID) + 0.05));
    expect(span).toBeCloseTo(4.478, 2);
    // Spread k colours geometrically across that span and the closest adjacent
    // pair is span^(1/(k-1)). This is an upper bound on the best achievable
    // minimum separation, attained only by a set that includes pure white and
    // sits exactly on the floor — which leaves no freedom for hue at all.
    const bestPossibleSeven = span ** (1 / 6);
    expect(bestPossibleSeven).toBeCloseTo(1.284, 2);
    expect(bestPossibleSeven).toBeLessThan(1.5);
    expect(DESIGN).toContain('1.28:1');
  });

  it('recomputes the closest pair independently of the palette module', () => {
    // This file's own arithmetic, deliberately not tools/lib/palette.mjs, so
    // agreement between the two is evidence rather than a tautology.
    const pairs = [];
    for (let i = 0; i < ELEMENTS.length; i += 1) {
      for (let j = i + 1; j < ELEMENTS.length; j += 1) {
        pairs.push({ a: ELEMENTS[i], b: ELEMENTS[j], ratio: contrast(ELEMENTS[i].hex, ELEMENTS[j].hex) });
      }
    }
    pairs.sort((x, y) => x.ratio - y.ratio);
    expect(pairs).toHaveLength(21);
    expect(pairs[0].a.id).toBe('amber');
    expect(pairs[0].b.id).toBe('aqua');
    expect(pairs[0].ratio.toFixed(2)).toBe('1.10');
    // Two pairs inside the CLASSIC five are the closest, so this was never a
    // SEVEN problem. Round 2 named INDIGO/VIOLET as the weakest pair; it is
    // THIRD, and round 4's test comment said fourth about its own sorted data.
    expect(spherePairs().map((pair) => pair.key)).toEqual(pairs.map((pair) => `${pair.a.id}|${pair.b.id}`));
  });

  /**
   * The round-4 defect this block exists for.
   *
   * §6.1's list was four hand-typed pairs. Every ratio in it was right and the
   * SET was wrong: it omitted AMBER↔ROSE (1.2470, third — a 0.002 gap from
   * VIOLET↔INDIGO) and published the fifth-closest instead. The old test sorted
   * all 21 pairs and then asserted `pairs[0]` plus four `toContain` substring
   * checks, so it validated every number and never the claim.
   *
   * These tests assert the CLAIM: the published rows are the k closest pairs,
   * in order, with the ratios this module computes.
   */
  describe('§6.1 publishes the closest pairs, as a set and in order', () => {
    const documented = documentedClosestPairs();

    it('is generated from the module rather than typed', () => {
      expect(DESIGN).toContain('tools/lib/palette.mjs');
      expect(documented).toHaveLength(PUBLISHED_CLOSEST_PAIRS);
      // The whole fenced block must be byte-identical to the generator's output.
      const start = DESIGN.indexOf('<!-- palette:closest-pairs:start -->');
      const end = DESIGN.indexOf('<!-- palette:closest-pairs:end -->');
      const block = DESIGN.slice(start + '<!-- palette:closest-pairs:start -->'.length, end).trim();
      expect(block).toBe(closestPairsMarkdown());
    });

    it('names exactly the k closest pairs, in ascending order', () => {
      const expected = closestPairs().map((pair) => `${pair.a.name}↔${pair.b.name}`);
      expect(documented.map((row) => row.pair)).toEqual(expected);
      // And nothing closer than the last published row is left out: the 6th
      // pair must be strictly worse than the 5th, or the list is arbitrary.
      const all = spherePairs();
      expect(all[PUBLISHED_CLOSEST_PAIRS].ratio).toBeGreaterThan(all[PUBLISHED_CLOSEST_PAIRS - 1].ratio);
    });

    it('quotes every ratio correctly', () => {
      closestPairs().forEach((pair, index) => {
        expect(documented[index].ratio, documented[index].pair).toBe(ratioText(pair.ratio));
      });
    });

    it('includes AMBER↔ROSE, the pair the hand-typed list dropped', () => {
      expect(documented.map((row) => row.pair)).toContain('AMBER↔ROSE');
      const amberRose = spherePairs().find((pair) => pair.key === 'amber|rose');
      const violetIndigo = spherePairs().find((pair) => pair.key === 'violet|indigo');
      // Third and effectively tied with the pair round 4 did name.
      expect(amberRose.ratio).toBeGreaterThan(violetIndigo.ratio);
      expect(amberRose.ratio - violetIndigo.ratio).toBeLessThan(0.01);
      // And §15's remedy must send the validation at it, since nothing else has.
      const open4 = DESIGN.slice(DESIGN.indexOf('4. **SEVEN colour separation'));
      expect(open4).toMatch(/start\s+with AMBER↔ROSE/u);
    });

    it('agrees with the independent bound this file computes', () => {
      expect(luminanceSpan()).toBeCloseTo(1.05 / (FLOOR * (luminance(VOID) + 0.05)), 10);
      expect(bestAchievableSeparation(ELEMENTS.length)).toBeCloseTo(1.284, 2);
      // Every published pair sits below the bound; that is the whole argument.
      for (const pair of closestPairs()) {
        expect(pair.ratio, `${pair.key}`).toBeLessThan(bestAchievableSeparation(ELEMENTS.length) * 1.1);
      }
    });
  });

  it('the withdrawn remedies really did make both pairs worse', () => {
    const byId = Object.fromEntries(ELEMENTS.map((element) => [element.id, element.hex]));
    expect(contrast('#3D8BFF', byId.violet)).toBeLessThan(contrast(byId.indigo, byId.violet));
    expect(contrast('#FF6FB0', byId.coral)).toBeLessThan(contrast(byId.rose, byId.coral));
    // They may be named where they are withdrawn; they may not be prescribed.
    expect(DESIGN).toMatch(/colour remedy is withdrawn/u);
    expect(DESIGN).not.toMatch(/move ROSE toward/u);
    // And they are not in the shipped palette.
    for (const element of ELEMENTS) {
      expect(element.hex).not.toBe('#3D8BFF');
      expect(element.hex).not.toBe('#FF6FB0');
    }
  });

  it('the document commits to the glyph as the guaranteed channel', () => {
    expect(DESIGN).toMatch(/the glyph is the\s+colour-blind channel/u);
    // Every element must carry a distinct glyph for that to be true.
    const glyphs = new Set(ELEMENTS.map((element) => element.glyph));
    expect(glyphs.size).toBe(ELEMENTS.length);
    for (const element of ELEMENTS) expect(DESIGN, element.glyph).toContain(element.glyph);
  });
});
